export function getToolById(id: string): ToolDefinition | undefined {
  return TOOLS.find((tool) => tool.id === id);
}

export function getToolByRoute(route: string): ToolDefinition | undefined {
  if (!route) return undefined;
  // normalize route: strip query string, hash, trailing slashes, index.html
  let cleanRoute = route.split('?')[0].split('#')[0];
  cleanRoute = cleanRoute.replace(/\/index\.html$/i, '');
  if (!cleanRoute.startsWith('/')) cleanRoute = `/${cleanRoute}`;
  if (cleanRoute.length > 1 && cleanRoute.endsWith('/')) {
    cleanRoute = cleanRoute.slice(0, -1);
  }

  // Alias mappings for legacy or alternative route formats
  const ALIASES: Record<string, string> = {
    '/pdf-protect': '/pdf-flatten',
    '/protect-pdf': '/pdf-flatten',
    '/flatten-pdf': '/pdf-flatten',
    '/pdf-rotate': '/rotate-pdf',
    '/crop-image': '/image-crop',
    '/rotate-image': '/image-rotate-flip',
    '/compress-image': '/image-compressor',
    '/resize-image': '/image-resizer',
    '/convert-image': '/image-converter',
    '/strip-exif': '/image-strip-exif',
    '/exif': '/image-strip-exif',
    '/filter-image': '/image-filter',
    '/photo-filter': '/image-filter',
  };

  if (ALIASES[cleanRoute]) {
    cleanRoute = ALIASES[cleanRoute];
  }

  return TOOLS.find((tool) => tool.route === cleanRoute || tool.id === cleanRoute.replace(/^\//, ''));
}

export function getRecommendedToolsForFile(file: File): ToolDefinition[] {
  const type = file.type.toLowerCase();
  const name = file.name.toLowerCase();

  if (type.includes('pdf') || name.endsWith('.pdf')) {
    return [
      getToolById('pdf-organizer')!,
      getToolById('compress-pdf')!,
      getToolById('merge-pdf')!,
      getToolById('split-pdf')!,
      getToolById('pdf-rotate')!,
      getToolById('pdf-to-images')!,
      getToolById('pdf-watermark')!,
    ].filter(Boolean);
  }

  if (type.startsWith('image/') || /\.(jpg|jpeg|png|webp|svg)$/i.test(name)) {
    return [
      getToolById('image-compressor')!,
      getToolById('image-resizer')!,
      getToolById('image-converter')!,
      getToolById('image-crop')!,
      getToolById('image-rotate-flip')!,
      getToolById('images-to-pdf')!,
      getToolById('image-strip-exif')!,
    ].filter(Boolean);
  }

  return TOOLS.slice(0, 6);
}
